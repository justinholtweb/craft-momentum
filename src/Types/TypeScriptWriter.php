<?php

declare(strict_types=1);

namespace JustinHoltWeb\Momentum\Types;

use CraftCms\Cms\Asset\Elements\Asset;
use CraftCms\Cms\Element\Eloquent\EloquentElement;
use CraftCms\Cms\Entry\Data\EntryType;
use CraftCms\Cms\Entry\Elements\Entry;
use CraftCms\Cms\Field\BaseRelationField;
use CraftCms\Cms\FieldLayout\FieldLayout;
use CraftCms\Cms\Section\Data\Section;
use CraftCms\Cms\Support\Facades\Sections;
use CraftCms\Cms\User\Elements\User;
use Illuminate\Support\Str;
use JustinHoltWeb\Momentum\Props\FieldRules;
use JustinHoltWeb\Momentum\Props\Transformers\Transformers;
use JustinHoltWeb\Momentum\Routing\InertiaTemplate;

/**
 * Writes TypeScript declarations for Momentum's page props (Pro): one
 * interface per entry type reached from an Inertia section, typed by the same
 * transformers that build the props, plus a `MomentumPages` map of component
 * name → page props.
 */
class TypeScriptWriter
{
    /** @var array<string, string> entry type uid → type name */
    private array $entryTypes = [];

    /** @var array<string, string> type name → declaration */
    private array $declarations = [];

    /** @var array<string, true> */
    private array $names = [];

    public function __construct(
        private readonly Transformers $transformers,
        private readonly FieldRules $rules,
        private readonly bool $deferEnabled = false,
    ) {}

    /**
     * @param  list<string>|null  $sectionHandles  Limit to these sections (default: every section with an Inertia template).
     */
    public function write(?array $sectionHandles = null): string
    {
        $pages = [];

        foreach (Sections::getAllSections() as $section) {
            /** @var Section $section */
            if ($sectionHandles !== null && ! in_array($section->handle, $sectionHandles, true)) {
                continue;
            }

            foreach ($section->getSiteSettings() as $siteSettings) {
                $component = InertiaTemplate::component($siteSettings->template);

                if ($component === null) {
                    continue;
                }

                foreach ($section->getEntryTypes() as $type) {
                    $pages[$component][] = $this->entryType($type);
                }
            }
        }

        $map = [];
        ksort($pages);

        foreach ($pages as $component => $types) {
            $map[] = '  '.self::literal($component).': MomentumPageProps<'.implode(' | ', array_unique($types)).'>;';
        }

        return implode("\n", [
            '// Generated by `php artisan craft:momentum:types`. Do not edit: re-run the command after changing fields.',
            '/* eslint-disable */',
            '',
            self::BASE,
            '',
            ...array_values($this->declarations),
            'export interface MomentumPages {',
            ...$map,
            '}',
            '',
        ]);
    }

    /**
     * The type name for an entry type, declaring it on first use.
     */
    public function entryType(EntryType $type): string
    {
        $key = (string) ($type->uid ?? $type->handle);

        if (isset($this->entryTypes[$key])) {
            return $this->entryTypes[$key];
        }

        $name = $this->uniqueName(Str::studly((string) $type->handle).'Entry');
        $this->entryTypes[$key] = $name;
        $this->declarations[$name] = ''; // reserve the slot (and stop recursion) before the fields refer back

        $fields = $this->fieldsOf($type->getFieldLayout(), $type->handle);
        $this->declarations[$name] = "export type {$name} = MomentumEntry<".self::literal((string) $type->handle).", {$fields}>;\n";

        return $name;
    }

    /**
     * An inline object type for a layout's fields, after excludes and renames.
     */
    public function fieldsOf(?FieldLayout $layout, ?string $qualifier): string
    {
        if ($layout === null) {
            return '{}';
        }

        $lines = [];

        foreach ($layout->getCustomFields() as $field) {
            $handle = $field->handle;

            if ($handle === null || $this->rules->excludes($handle, $qualifier)) {
                continue;
            }

            $type = $this->transformers->for($field)?->typeScript($field, $this) ?? 'unknown';

            if ($type === 'never') {
                continue;
            }

            $optional = $this->deferEnabled && $this->rules->defers($handle, $qualifier) ? '?' : '';
            $lines[] = self::key($this->rules->propName($handle, $qualifier)).$optional.': '.$type;
        }

        return $lines === [] ? '{}' : '{ '.implode('; ', $lines).' }';
    }

    public function relationTarget(BaseRelationField $field): string
    {
        $elementType = $field::elementType();

        return match (true) {
            is_a($elementType, Entry::class, true) => $this->entryTargets($field),
            is_a($elementType, Asset::class, true) => 'MomentumAsset',
            is_a($elementType, User::class, true) => 'MomentumUser',
            is_a($elementType, EloquentElement::class, true) => 'MomentumEloquentElement',
            default => 'MomentumElementRef',
        };
    }

    public static function literal(string $value): string
    {
        return json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);
    }

    public static function key(string $name): string
    {
        return preg_match('/^[A-Za-z_$][A-Za-z0-9_$]*$/', $name) ? $name : self::literal($name);
    }

    private function entryTargets(BaseRelationField $field): string
    {
        $sources = $field->sources;

        if (! is_array($sources)) {
            return 'MomentumEntry';
        }

        $types = [];

        foreach ($sources as $source) {
            if (! str_starts_with($source, 'section:')) {
                return 'MomentumEntry';
            }

            $section = Sections::getSectionByUid(substr($source, 8));

            foreach ($section?->getEntryTypes() ?? [] as $type) {
                $types[] = $this->entryType($type);
            }
        }

        return $types === [] ? 'MomentumEntry' : '('.implode(' | ', array_unique($types)).')';
    }

    private function uniqueName(string $name): string
    {
        $base = $name;

        for ($i = 2; isset($this->names[$name]); $i++) {
            $name = $base.$i;
        }

        $this->names[$name] = true;

        return $name;
    }

    private const string BASE = <<<'TS'
        export interface MomentumElementRef {
          id: number;
          title: string | null;
          url: string | null;
        }

        export interface MomentumEntry<TType extends string = string, TFields = Record<string, unknown>> extends MomentumElementRef {
          uid: string;
          slug: string | null;
          uri: string | null;
          /** Null for nested (Matrix) entries. */
          section: string | null;
          type: TType;
          postDate: string | null;
          dateUpdated: string | null;
          fields: TFields;
        }

        export interface MomentumAsset<TFields = Record<string, unknown>> extends MomentumElementRef {
          uid: string;
          alt: string | null;
          filename: string;
          kind: string;
          mimeType: string | null;
          size: number | null;
          width: number | null;
          height: number | null;
          focalPoint: { x: number; y: number } | null;
          /** Named transforms from Momentum's settings (images only). */
          transforms: Record<string, string | null> | null;
          fields: TFields;
        }

        export interface MomentumUser {
          id: number;
          name: string | null;
        }

        export interface MomentumEloquentElement extends MomentumElementRef {
          attributes: Record<string, unknown>;
          fields: Record<string, unknown>;
        }

        export interface MomentumRichText {
          html: string;
          chunks: Array<{ type: 'markup'; html: string } | { type: 'entry'; entry: MomentumEntry | number | null }>;
        }

        export interface MomentumSite {
          handle: string;
          name: string;
          language: string;
          baseUrl: string | null;
        }

        export interface MomentumAlternate {
          site: string;
          language: string;
          url: string;
          current: boolean;
        }

        export interface MomentumSharedProps {
          site: MomentumSite;
          currentUser?: MomentumUser | null;
          errors: Record<string, string>;
        }

        export type MomentumPageProps<TEntry> = MomentumSharedProps & {
          entry: TEntry;
          alternates: MomentumAlternate[];
        };
        TS;
}
